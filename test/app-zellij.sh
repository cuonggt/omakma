# zellij: config.kdl is written only when absent and then edited in place by
# `omakma theme`, while themes/<name>.kdl is recopied. The interesting case is
# the real one -- zellij rewrites config.kdl itself, moving Omakma's aside.

echo "fresh Omakma state"
HOME_DIR=$(sandbox_home zellij-fresh)
mkdir -p "$HOME_DIR/.config/zellij/themes"
cp "$OMAKMA_PATH/configs/zellij.kdl" "$HOME_DIR/.config/zellij/config.kdl"
cp "$OMAKMA_PATH/themes/default/zellij.kdl" "$HOME_DIR/.config/zellij/themes/default.kdl"

run_script "$HOME_DIR" uninstall terminal/app-zellij.sh
assert_gone "theme file removed" "$HOME_DIR/.config/zellij/themes/default.kdl"
assert_gone "config.kdl removed" "$HOME_DIR/.config/zellij/config.kdl"
assert_gone "whole directory pruned" "$HOME_DIR/.config/zellij"

echo "zellij has rewritten config.kdl itself"
HOME_DIR=$(sandbox_home zellij-rewritten)
mkdir -p "$HOME_DIR/.config/zellij/themes"
cp "$OMAKMA_PATH/themes/default/zellij.kdl" "$HOME_DIR/.config/zellij/themes/default.kdl"
{
  echo "// THIS FILE WAS AUTOGENERATED BY ZELLIJ"
  echo 'keybinds clear-defaults=true {}'
} >"$HOME_DIR/.config/zellij/config.kdl"

run_script "$HOME_DIR" uninstall terminal/app-zellij.sh
assert_gone "Omakma's theme file still removed" "$HOME_DIR/.config/zellij/themes/default.kdl"
assert_exists "zellij's own config.kdl kept" "$HOME_DIR/.config/zellij/config.kdl"
assert_exists "directory kept with it" "$HOME_DIR/.config/zellij"
assert_says "says it kept config.kdl" "config.kdl: it differs"

echo "theme switched to catppuccin"
HOME_DIR=$(sandbox_home zellij-catppuccin)
mkdir -p "$HOME_DIR/.config/zellij/themes"
cp "$OMAKMA_PATH/themes/catppuccin/zellij.kdl" "$HOME_DIR/.config/zellij/themes/catppuccin.kdl"

run_script "$HOME_DIR" uninstall terminal/app-zellij.sh
assert_gone "the switched-to theme file is ours too" "$HOME_DIR/.config/zellij/themes/catppuccin.kdl"

echo "nothing installed"
HOME_DIR=$(sandbox_home zellij-absent)
run_script "$HOME_DIR" uninstall terminal/app-zellij.sh
assert_gone "no config directory conjured up" "$HOME_DIR/.config/zellij"
